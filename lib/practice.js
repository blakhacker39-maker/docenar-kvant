/* Повторная практика: конечный банк, новые числовые условия и история подходов. */
(function () {
  'use strict';
  var QB = window.QB;
  function num(v) { return String(Math.round(v * 1e6) / 1e6).replace('.', ','); }
  function variant(mid, i) {
    var x = i + 1, q, a, unit, hint;
    switch (mid) {
      case 'm01': case 'm02':
        var wavelength = [310, 500, 800][i];
        q = 'Найдите энергию фотона с длиной волны ' + wavelength + ' нм. Используйте hc = 1240 эВ·нм.';
        a = 1240 / wavelength; unit = 'эВ'; hint = 'Энергия фотона: $E = \\frac{hc}{λ}$.'; break;
      case 'm03':
        q = 'Энергия фотона ' + (4 + x) + ' эВ, работа выхода 2,5 эВ. Найдите максимальную кинетическую энергию фотоэлектрона.';
        a = 4 + x - 2.5; unit = 'эВ'; hint = 'Из энергии фотона вычтите работу выхода.'; break;
      case 'm04':
        x += 1;
        q = 'При увеличении частоты на ' + (2 * x) + '·10<sup>14</sup> Гц задерживающее напряжение выросло на ' + num(0.83 * x) + ' В. Найдите постоянную Планка в единицах 10<sup>−34</sup> Дж·с. e = 1,6·10<sup>−19</sup> Кл.';
        a = 6.64; unit = '·10<sup>−34</sup> Дж·с'; hint = '$h = \\frac{e·ΔU}{Δν}$. Учтите степени десяти.'; break;
      case 'm05':
        q = 'Свет интенсивностью ' + (300 * x) + ' Вт/м² падает нормально на полностью поглощающую поверхность. Найдите давление в мкПа. c = 3·10<sup>8</sup> м/с.';
        a = x; unit = 'мкПа'; hint = 'Для поглощающей поверхности $p = \\frac{I}{c}$; 1 мкПа = 10⁻⁶ Па.'; break;
      case 'm06':
        q = 'В условной масштабной модели радиус атома 10⁻¹⁰ м, радиус ядра ' + x + '·10⁻¹⁵ м. Во сколько раз первый радиус больше второго?';
        a = 1e5 / x; unit = 'раз'; hint = 'Разделите радиус атома на радиус ядра; это модель масштаба, не размеры конкретного изотопа.'; break;
      case 'm07':
        var n = x + 2;
        q = 'В модели Бора $E_n = −\\frac{13,6}{n^2}$ эВ. Найдите энергию атома водорода при n = ' + n + '.';
        a = -13.6 / (n * n); unit = 'эВ'; hint = 'Возведите n в квадрат и сохраните отрицательный знак.'; break;
      case 'm08':
        var energy = [1.89, 2.86, 3.02][i];
        q = 'Энергия испущенного фотона ' + num(energy) + ' эВ. Найдите длину волны. hc = 1240 эВ·нм.';
        a = 1240 / energy; unit = 'нм'; hint = '$λ = \\frac{hc}{E}$.'; break;
      case 'm09':
        q = 'Лазер мощностью ' + (5 * x) + ' мВт даёт пучок площадью 5·10⁻⁶ м². Найдите интенсивность в кВт/м².';
        a = x; unit = 'кВт/м²'; hint = '$I = \\frac{P}{S}$. Сначала переведите мВт в Вт, затем Вт/м² в кВт/м².'; break;
      case 'm10':
        var isotope = [[12,6,'C'],[16,8,'O'],[23,11,'Na']][i];
        q = 'Сколько нейтронов в ядре {' + isotope.join(',') + '}?';
        a = isotope[0] - isotope[1]; unit = ''; hint = 'N = A − Z.'; break;
      case 'm11': case 'm13': case 'm19':
        var mass = 0.01 * x;
        q = (mid === 'm11' ? 'Дефект масс ядра равен ' : 'В учебной модели реакции суммарная масса покоя уменьшилась на ') + num(mass) + ' а.е.м. Найдите ' + (mid === 'm11' ? 'энергию связи' : 'выделившуюся энергию') + '. 1 а.е.м. соответствует 931,5 МэВ.';
        a = mass * 931.5; unit = 'МэВ'; hint = 'Умножьте изменение массы в а.е.м. на 931,5 МэВ/а.е.м.'; break;
      case 'm12':
        var nucleus = [[4,28.3],[7,39.2],[56,492.2]][i];
        q = 'Ядро содержит ' + nucleus[0] + ' нуклонов, энергия связи ' + num(nucleus[1]) + ' МэВ. Найдите удельную энергию связи.';
        a = nucleus[1] / nucleus[0]; unit = 'МэВ/нуклон'; hint = 'Разделите энергию связи на число нуклонов.'; break;
      case 'm14':
        q = 'В цепочке произошло ' + x + (x === 1 ? ' α-распад' : ' α-распада') + ' и 2 β⁻-распада. На сколько уменьшилось массовое число?';
        a = 4 * x; unit = ''; hint = 'Каждый α-распад уменьшает A на 4; β⁻-распад не меняет A.'; break;
      case 'm15': case 'm22':
        q = 'Период полураспада равен ' + (4 * x) + ' суткам. За сколько суток число нераспавшихся ядер уменьшится в 8 раз?';
        a = 12 * x; unit = 'сут'; hint = '8 = 2³: пройдут три периода полураспада.'; break;
      case 'm16':
        x = [1,3,4][i];
        q = 'Какова вероятность, что ядро не распадётся за ' + x + (x === 1 ? ' период' : ' периода') + ' полураспада? Ответ дайте десятичной дробью.';
        a = Math.pow(0.5, x); unit = ''; hint = 'Вероятность сохраниться за каждый период равна 1/2; перемножьте вероятности.'; break;
      case 'm17':
        q = 'Образец массой 2 кг поглотил ' + num(0.02 * x) + ' Дж энергии излучения. Найдите поглощённую дозу в мГр.';
        a = 10 * x; unit = 'мГр'; hint = '$D = \\frac{E}{m}$; 1 Гр = 1 Дж/кг = 1000 мГр. Это расчётная модель, не рекомендация по безопасности.'; break;
      case 'm18':
        q = 'В модели цепной реакции в начальном поколении 50 нейтронов, k = 2. Сколько нейтронов будет после ' + x + (x === 1 ? ' умножения' : ' умножений') + '?';
        a = 50 * Math.pow(2, x); unit = ''; hint = 'N = N₀·kⁿ.'; break;
      case 'm20':
        q = 'В модели трека заряд и магнитное поле постоянны. Импульс частицы увеличили в ' + (x + 1) + ' раза. Во сколько раз увеличится радиус траектории?';
        a = x + 1; unit = 'раз'; hint = '$R = \\frac{p}{|q|B}$: радиус прямо пропорционален импульсу.'; break;
      case 'm21':
        x += 1;
        q = 'Источник мощностью ' + x + ' мВт испускает фотоны с энергией 2 эВ. Сколько фотонов испускается за секунду в единицах 10¹⁵? 1 эВ = 1,6·10⁻¹⁹ Дж.';
        a = 3.125 * x; unit = '·10¹⁵'; hint = '$N = \\frac{P}{E}$. Переведите мощность и энергию в СИ.'; break;
    }
    return {id:'practice-v'+i,type:'num',q:q,a:a,unit:unit,tol:['m10','m14','m18'].indexOf(mid)>=0?0:0.02,
      hint:hint,why:hint+' Результат: '+num(a)+(unit?' '+unit:'')+'.',back:'lab'};
  }
  QB.practiceBank = function (m) {
    return m.quiz.map(function(q){ return Object.assign({}, q, {id:'practice-'+q.id}); })
      .concat([0,1,2].map(function(i){return variant(m.id,i);}));
  };
  QB.practiceRound = function (bank, state, original) {
    var seen = state.answers || (state.answers = {});
    var ranked = bank.map(function(q,i){
      var r=seen[q.id], old=original[q.id.replace('practice-','')];
      return {q:q,i:i,count:r?r.tries:old&&old.first!=null?1:0,wrong:r?r.ok===false:old&&old.ok===false};
    });
    var fresh=ranked.filter(function(x){return !x.count;});
    var pool=fresh.length?fresh:ranked;
    pool.sort(function(a,b){return a.count-b.count || Number(b.wrong)-Number(a.wrong) || a.i-b.i;});
    state.repeat=!fresh.length;
    state.current=pool.slice(0,3).map(function(x){return x.q.id;});
    state.round=(state.round||0)+1;
    state.current.forEach(function(id){if(seen[id]){seen[id].ok=null;delete seen[id].value;}});
    return state.current;
  };
})();
